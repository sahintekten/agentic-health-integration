CREATE TABLE LB_PT (
    PT_REF      INTEGER NOT NULL,
    PT_NM       VARCHAR(20),
    PT_DOB      INTEGER,
    PT_SX       SMALLINT,
    CRT_DT      BIGINT
);

CREATE TABLE LB_TST_CODES (
    TST_CD      VARCHAR(8) NOT NULL,
    TST_DESC    VARCHAR(20),
    LOINC_CD    VARCHAR(10),
    DFLT_UOM    VARCHAR(12),
    ACTV_FLG    CHAR(1)
);

CREATE TABLE LB_RSLT (
    RSLT_ID     INTEGER NOT NULL,
    PT_REF      INTEGER,
    TST_CD      VARCHAR(8),
    LB_VAL1     VARCHAR(16),
    LB_VAL2     VARCHAR(16),
    UOM         VARCHAR(12),
    RSLT_DT     BIGINT,
    FLG         CHAR(1),
    STS         CHAR(1),
    ENT_USR     VARCHAR(8)
);

CREATE INDEX LB_PT_IX1 ON LB_PT (PT_REF);
CREATE INDEX LB_RSLT_IX1 ON LB_RSLT (PT_REF);
CREATE INDEX LB_RSLT_IX2 ON LB_RSLT (RSLT_DT);
